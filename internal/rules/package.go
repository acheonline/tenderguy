package rules

import (
	"tenderguy/internal/reqs"
	"tenderguy/internal/trace"
)

// Package — вход движка: пакет документов, собранный вызывающим кодом (CLI).
// Движок не обходит каталог и не парсит форматы сам, поэтому scanner и parser
// остаются за его пределами: сопоставление обхода с моделями разбора делает
// cmd, а правила получают готовые данные. JSON-тегов у полей нет намеренно —
// пакет не сериализуется, это вход проверок, а не отчёт.
type Package struct {
	// Root — каталог пакета, как его передал оператор через --input-dir.
	Root string
	// Docs — разобранные поддерживаемые документы: фрагменты с адресами
	// (P1.6) и карточка реквизитов (P1.5).
	Docs []Doc
	// Files — все файлы обхода, включая неподдерживаемые: сверка состава
	// пакета (P2.4) обязана видеть архивы и служебные файлы, а не только те
	// документы, которые удалось разобрать.
	Files []File
	// Failed — поддерживаемые документы, которые разобрать не удалось: по ним
	// отчёт неполон, и это видно в Report.
	Failed []Failed
}

// Doc — разобранный документ пакета.
type Doc struct {
	// Path — путь к файлу ровно в той форме, в которой его передал оператор:
	// с ним совпадает trace.Ref.File в адресах замечаний.
	Path string
	// RelPath — путь от корня пакета: по нему документ ищется в описи.
	RelPath string
	// Format — docx, xlsx или pdf.
	Format string
	// Fragments — содержимое документа с адресами; из них берётся цитата и
	// адрес замечания.
	Fragments []trace.Fragment
	// Reqs — карточка реквизитов файла (значения уже несут свои адреса).
	Reqs *reqs.Card
}

// File — файл обхода: и разобранный документ, и архив, и служебный файл.
type File struct {
	RelPath   string
	Name      string
	Kind      string
	Supported bool
	// Note — классификационная пометка обхода (например «архив вне перечня P1»).
	Note string
	// Problem — состояние файла, требующее внимания (ссылка, ошибка чтения).
	Problem string
}

// Failed — документ, который обход нашёл, но разобрать не удалось. Попадает и
// в отчёт: проверка по неполному входу неполна, и человек обязан это видеть.
type Failed struct {
	Path  string `json:"path"`
	Error string `json:"error"`
}
