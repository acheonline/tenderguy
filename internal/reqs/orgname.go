package reqs

// Задача P2.2: наименование юридического лица (ИП) как реквизит карточки.
// Критерий эпика P2 требует сверять наименование наравне с ИНН/КПП/ОГРН,
// поэтому у значения тот же контракт, что у числовых реквизитов P1.5: оно
// нормализовано (Valid/Reason — про проверку), несёт метку поля формы и адрес
// в источнике (P1.6), а повторы сливаются Card.add.
//
// Извлечение строго по метке: «наименование» без квалификатора — ещё и колонка
// спецификаций товара, поэтому значение под голой меткой принимается только
// когда в нём видна организационно-правовая форма.

import (
	"regexp"
	"sort"
	"strings"
	"unicode"

	"tenderguy/internal/trace"
)

// reOrgNameLabel — строка-метка наименования: «Полное наименование: ООО „Ромашка“»,
// «Фирменное наименование — …», «Наименование участника закупки: …». В строке
// таблицы .docx/.xlsx метка и значение — соседние клетки, склеенные табуляцией,
// поэтому значение берётся до первого таба, а не до конца строки: иначе в
// значение наименования попали бы ИНН и цена из следующих колонок.
//
// Группа 1 — префикс-квалификатор (полное/фирменное/сокращённое/краткое),
// группа 2 — уточнение поля (организации, участника закупки, …), группа 3 —
// значение. По группам 1–2 scanOrgName отличает поле карточки участника от
// колонки «Наименование» в спецификации. После «наименование» обязателен
// небуквенный символ: RE2 не знает lookahead, а без границы литерал совпал бы
// с префиксом творительного падежа — «наименованием ООО „Ромашка“» дало бы
// значение «м ООО „Ромашка“». \b не годится: в Go это ASCII-граница.
var reOrgNameLabel = regexp.MustCompile(
	`(?i)((?:полное|фирменное|сокращ[её]нное|краткое)\s+)?наименование` +
		`[^\p{L}][\t ]*(организации|юридического\s+лица|юр\.?\s*лица|участника(?:\s+закупки)?|поставщика|подрядчика|исполнителя|продавца|покупателя|заявителя|компании|фирмы|общества|предприятия)?` +
		`[\t ]*[:—–-]?[\t ]*([^\t]+)`)

// orgNameSkip — то, что «наименование» описывает помимо организации: товарные
// позиции спецификаций, поля закупки, договора и банковских реквизитов
// (банковские реквизиты вне скоупа P2.2). Проверяется первое слово значения,
// поэтому «Работы по ремонту кровли» отсекается даже под меткой «Полное
// наименование»: в спецификациях она относится к товару, а потерянное имя
// организации вида «Банк „Зенит“» — осознанная плата за чистоту карточки.
var orgNameSkip = map[string]bool{
	"товар": true, "товара": true, "товаров": true, "товарное": true,
	"товарная": true, "товарный": true,
	"продукция": true, "продукции": true, "продукт": true,
	"работа": true, "работы": true, "работ": true,
	"услуга": true, "услуги": true, "услуг": true,
	"оборудование": true, "оборудования": true,
	"материал": true, "материала": true, "материалов": true, "материальные": true,
	"предмет": true, "предмета": true,
	"закупка": true, "закупки": true, "проект": true, "проекта": true,
	"договор": true, "договора": true, "контракт": true, "контракта": true,
	"лот": true, "лота": true, "позиция": true, "позиции": true,
	"спецификация": true, "спецификации": true,
	"документ": true, "документа": true, "документация": true, "документации": true,
	"показатель": true, "показателя": true,
	"единица": true, "единицы": true, "измерение": true, "измерения": true,
	"графа": true, "графы": true, "столбец": true, "столбца": true,
	"поле": true, "поля": true, "значение": true, "значения": true,
	"реквизит": true, "реквизита": true, "реквизиты": true,
	"банк": true, "банка": true, "счет": true, "счета": true,
}

// scanOrgName извлекает наименование по метке (критерий 1 P2.2). Значение без
// ОПФ из карточки не выбрасывается, а помечается Valid=false с причиной
// (критерий 6): расхождение наименований — предмет замечания P2.3.
func (c *Card) scanOrgName(frag trace.Fragment, pos int, line string) {
	for _, m := range reOrgNameLabel.FindAllStringSubmatchIndex(line, -1) {
		// Метка с квалификатором («полное наименование», «наименование
		// участника») — поле карточки участника: берём значение как есть.
		strong := m[2] != -1 || m[4] != -1
		raw := cleanValue(line[m[6]:m[7]])
		if raw == "" || orgNameSkip[firstWord(raw)] {
			continue
		}
		norm := NormalizeOrgName(raw)
		if norm == "" {
			continue
		}
		hasOPF := orgNameHasOPF(norm)
		// Голый «Наименование» — ещё и шапка спецификации: значение соседней
		// клетки («Кол-во», «Болт М6») наименованием организации не является.
		// Без квалификатора метки принимаем только значение с видимой ОПФ —
		// в строке данных xlsx («Наименование → ООО „Ромашка“») она есть.
		if !strong && !hasOPF {
			continue
		}
		item := Item{
			Kind: KindOrgName, Value: norm, Raw: raw, Valid: hasOPF,
			Label: matchedLabel(line, m[0], m[6]),
		}
		if !hasOPF {
			item.Reason = "в наименовании нет организационно-правовой формы (ООО, ПАО, ИП, …)"
		}
		c.add(located(frag, pos, m[6], item))
	}
}

// orgQuotes — кавычки всех видов и скобки заменяются пробелом, а не сохраняются:
// прямая кавычка " не различает открытие и закрытие, парность не восстановить,
// а на тождество имён «ООО „Ромашка“» и «ООО "Ромашка"» форма кавычек влиять
// не должна. Пробел вместо кавычки заодно разделяет «ООО«Ромашка»» на два токена.
var orgQuotes = strings.NewReplacer(
	"«", " ", "»", " ", "„", " ", "\u201C", " ", "\u201D", " ",
	"\u2018", " ", "\u2019", " ", "'", " ", "\"", " ", "`", " ",
	"(", " ", ")", " ",
)

// opfPairs — таблица ОПФ: полная форма приводится к сокращённой, чтобы
// «Общество с ограниченной ответственностью „Ромашка“» и «ООО „Ромашка“»
// нормализовались в одну строку (критерий 2 P2.2). Порядок применения — от
// самых длинных фраз: «публичное акционерное общество» обязано замениться
// раньше, чем его подстрока «акционерное общество».
var opfPairs = sortedOPFPairs()

func sortedOPFPairs() []struct{ full, short string } {
	pairs := []struct{ full, short string }{
		{"общество с ограниченной ответственностью", "ооо"},
		{"общество с дополнительной ответственностью", "одо"},
		{"публичное акционерное общество", "пао"},
		{"непубличное акционерное общество", "нао"},
		{"открытое акционерное общество", "оао"},
		{"закрытое акционерное общество", "зао"},
		{"акционерное общество", "ао"},
		{"индивидуальный предприниматель", "ип"},
		{"товарищество с ограниченной ответственностью", "тоо"},
		{"федеральное государственное унитарное предприятие", "фгуп"},
		{"государственное унитарное предприятие", "гуп"},
		{"муниципальное унитарное предприятие", "муп"},
		{"автономная некоммерческая организация", "ано"},
		{"некоммерческая организация", "нко"},
		{"унитарное предприятие", "уп"},
		// Скобки в «крестьянское (фермерское) хозяйство» к этому шагу уже
		// заменены пробелом — таблица работает по нормализованному тексту.
		{"крестьянское фермерское хозяйство", "кфх"},
	}
	sort.SliceStable(pairs, func(i, j int) bool { return len(pairs[i].full) > len(pairs[j].full) })
	return pairs
}

// opfShort — сокращения, которые сами являются маркером ОПФ.
var opfShort = map[string]bool{
	"ооо": true, "одо": true, "пао": true, "нао": true, "оао": true,
	"зао": true, "ао": true, "ип": true, "тоо": true, "гуп": true,
	"муп": true, "фгуп": true, "ано": true, "нко": true, "кфх": true,
}

// opfWords — ОПФ, которые не принято сокращать: их наличие в нормализованном
// имени тоже считается признаком организационно-правовой формы.
var opfWords = map[string]bool{
	"товарищество": true, "кооператив": true, "предприятие": true,
	"учреждение": true, "фонд": true, "ассоциация": true, "союз": true,
	"концерн": true, "компания": true, "фирма": true, "общество": true,
	"артель": true,
}

// NormalizeOrgName приводит наименование организации к форме, пригодной для
// сравнения (критерий 2 P2.2): регистр и «ё» не учитываются, кавычки всех
// видов убираются, пробелы (включая NBSP, который Word ставит после
// сокращений) схлопываются, полная ОПФ заменяется сокращённой, пунктуация по
// краям снимается. Пустой результат означает, что нормализовывать было нечего,
// — SameOrgName трактует это как «не найдено».
func NormalizeOrgName(s string) string {
	n := strings.ToLower(s)
	n = strings.ReplaceAll(n, "ё", "е")
	n = orgQuotes.Replace(n)
	n = collapseSpace(n)
	for _, p := range opfPairs {
		n = strings.ReplaceAll(n, p.full, p.short)
	}
	return strings.Trim(collapseSpace(n), ".,;:!?-–—() \t")
}

// SameOrgName сравнивает два наименования организации после нормализации
// (критерий 4 P2.2). Контракт трёхзначный — см. Match: «не эквивалентно» и
// «не найдено» обязаны различаться, иначе P2.3 сообщил бы о расхождении там,
// где значение просто не извлечено из одного из документов.
func SameOrgName(a, b string) Match {
	return compareNormalized(NormalizeOrgName(a), NormalizeOrgName(b))
}

// orgNameHasOPF — проверка наименования: в нормализованном имени есть токен ОПФ
// (сокращение из opfPairs либо слово, которое не сокращают). Без ОПФ значение
// подозрительно — это может быть название товара или неполное имя.
func orgNameHasOPF(norm string) bool {
	for _, tok := range strings.Fields(norm) {
		if t := strings.Trim(tok, ".,;:!?-–—()"); opfShort[t] || opfWords[t] {
			return true
		}
	}
	return false
}

// reValueStop — начало следующего реквизита внутри извлечённого значения: в
// абзаце анкеты «Полное наименование: ООО „Ромашка“. ИНН 7703…» значение
// наименования обязано закончиться перед «ИНН». Числовые реквизиты
// (ИНН/КПП/ОГРН/БИК/СНИЛС) отсекаются, когда за ними стоит цифра, текстовые
// (наименование/адрес/телефон/банк…) — когда за ними стоит разделитель поля:
// без этого «ПАО „Банк ВТБ“» потеряло бы хвост на слове «банк».
var reValueStop = regexp.MustCompile(
	`(?i)(?:^|[^\p{L}])(` +
		`(?:инн|кпп|огрнип|огрн|бик|снилс)[\t ]*(?::[\t ]*)?\d` +
		`|(?:наименование|адрес|местонахождение|телефон|телефакс|факс|e-?mail|почта|сайт|банк)\s*[:—–-])`)

// cleanValue обрезает значение поля по началу следующего реквизита и снимает
// пунктуацию по краям: строка формы редко совпадает с границами поля, а «. ИНН»
// в хвосте наименования принадлежит уже другому реквизиту.
func cleanValue(s string) string {
	s = strings.TrimSpace(s)
	if m := reValueStop.FindStringSubmatchIndex(s); m != nil {
		s = strings.TrimSpace(s[:m[2]])
	}
	return strings.Trim(s, " \t.,;:!?-–—")
}

// matchedLabel — текст найденной метки без разделителя («Полное наименование»,
// «Юридический адрес»): подсказка человеку, какое поле формы прочитано.
func matchedLabel(line string, start, valueStart int) string {
	return strings.Trim(line[start:valueStart], " \t:;,—–-")
}

// firstWord — первое слово значения: им проверяются списки пропуска (orgNameSkip,
// addressSkip). Разделители — всё, что не буква и не цифра, поэтому «товара:»
// и «товар-позиция» дают «товара» и «товар».
func firstWord(s string) string {
	words := splitWords(s)
	if len(words) == 0 {
		return ""
	}
	return strings.ToLower(words[0])
}

// lastWord — последнее слово перед найденной меткой: им проверяется
// «почтовый адрес» и «электронный адрес», которые юридическим адресом не
// являются, но голую метку «адрес» содержат.
func lastWord(s string) string {
	words := splitWords(s)
	if len(words) == 0 {
		return ""
	}
	return strings.ToLower(words[len(words)-1])
}

func splitWords(s string) []string {
	return strings.FieldsFunc(s, func(r rune) bool {
		return !unicode.IsLetter(r) && !unicode.IsDigit(r)
	})
}

// collapseSpace сводит любые пробельные символы (включая NBSP и узкий NBSP из
// Word) к одиночному пробелу и убирает пробелы по краям.
func collapseSpace(s string) string {
	s = strings.NewReplacer("\u00A0", " ", "\u202F", " ", "\u2007", " ", "\t", " ").Replace(s)
	return strings.Join(strings.Fields(s), " ")
}
