func TestNormalizeAddress(t *testing.T) {
	tests := []struct {
		name string
		in   string
		want string
	}{
		{"сокращения и полные слова к общей форме", "г. Москва, ул. Ленина, д. 1", "г москва ул ленина д 1"},
		{"полные слова", "город Москва улица Ленина дом 1", "г москва ул ленина д 1"},
		{"офис и помещение", "ул. Ленина, д. 5, оф. 12", "ул ленина д 5 оф 12"},
		{"офис полностью", "ул. Ленина, д. 5, офис 12", "ул ленина д 5 оф 12"},
		{"запятые произвольны", "190000 г Санкт-Петербург", "190000 г санкт-петербург"},
		{"индекс сохраняется токеном", "190000, г. Санкт-Петербург, Невский пр-кт, д. 1", "190000 г санкт-петербург невский пр-кт д 1"},
		{"проспект полностью", "Невский проспект, д. 1", "невский пр-кт д 1"},
		{"инвертированная пара город", "Москва г", "г москва"},
		{"инвертированная пара улица", "Ленина ул, д. 1", "ул ленина д 1"},
		{
			"тип между двумя именами не инвертируется — осознанное ограничение",
			"респ Татарстан г Казань",
			"респ татарстан г казань",
		},
		{"тире как разделитель частей", "г. Москва — ул. Ленина", "г москва ул ленина"},
		{"дефис в номере дома не трогается", "ул. Ленина, д. 5-а", "ул ленина д 5-а"},
		{"скобки-уточнение", "ул. Ленина, д. 5 (литер А), оф. 3", "ул ленина д 5 литер а оф 3"},
		{"ё приводится к е", "г. Егорьевск", "г егорьевск"},
		{"регистр не важен", "Г. МОСКВА", "г москва"},
		{"пустая строка", "", ""},
		{"только разделители", ",, — ", ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := NormalizeAddress(tt.in); got != tt.want {
				t.Errorf("NormalizeAddress(%q) = %q, хотим %q", tt.in, got, tt.want)
			}
		})
	}
}

func TestSameAddress(t *testing.T) {
	tests := []struct {
		name string
		a, b string
		want Match
	}{
		{
			"сокращения и полные слова не влияют",
			"190000, г. Санкт-Петербург, Невский пр-кт, д. 1, оф. 5",
			"190000 г Санкт-Петербург Невский проспект дом 1 офис 5",
			MatchEqual,
		},
		{
			"полная и сокращённая запись улицы",
			"г. Москва, улица Ленина, д. 3",
			"г Москва ул. Ленина д 3",
			MatchEqual,
		},
		{"разные города", "г. Москва, ул. Ленина, д. 1", "г. Тверь, ул. Ленина, д. 1", MatchDifferent},
		{"разные дома", "г. Москва, ул. Ленина, д. 1", "г. Москва, ул. Ленина, д. 2", MatchDifferent},
		{"одно значение пусто — не найдено", "г. Москва", "", MatchMissing},
		{"оба пустые — не найдено", "", "  ", MatchMissing},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := SameAddress(tt.a, tt.b); got != tt.want {
				t.Errorf("SameAddress(%q, %q) = %v, хотим %v", tt.a, tt.b, got, tt.want)
			}
		})
	}
}

func TestExtractAddress(t *testing.T) {
	tests := []struct {
		name  string
		line  string
		value string // "" — значение извлекаться не должно
		valid bool
		label string
	}{
		{
			"юридический адрес",
			"Юридический адрес: 190000, г. Санкт-Петербург, Невский пр-кт, д. 1",
			"190000 г санкт-петербург невский пр-кт д 1", true, "Юридический адрес",
		},
		{
			"место нахождения",
			"Место нахождения — г. Москва, ул. Ленина, д. 1",
			"г москва ул ленина д 1", true, "Место нахождения",
		},
		{
			"адрес местонахождения",
			"Адрес местонахождения: г. Москва, ул. Ленина, д. 1",
			"г москва ул ленина д 1", true, "Адрес местонахождения",
		},
		{
			"голая метка с двоеточием",
			"Адрес: г. Тверь, ул. Советская, д. 2",
			"г тверь ул советская д 2", true, "Адрес",
		},
		{
			"значение до первого таба",
			"Адрес\tг. Тверь, ул. Советская, д. 2\tИНН",
			"г тверь ул советская д 2", true, "Адрес",
		},
		{
			"значение без признаков адреса остаётся подозрительным",
			"Юридический адрес: уточняется",
			"уточняется", false, "Юридический адрес",
		},
		{
			"один индекс — признак адреса",
			"Юридический адрес: 190000",
			"190000", true, "Юридический адрес",
		},
		{"почтовый адрес не юридический", "Почтовый адрес: 190000, г. Санкт-Петербург", "", false, ""},
		{"электронный адрес отсекается", "Электронный адрес: info@romashka.ru", "", false, ""},
		{"адрес поставки отсекается", "Адрес: поставки товара, склад №3", "", false, ""},
		{"e-mail под голой меткой отсекается", "Адрес: romashka@mail.ru", "", false, ""},
		{"фраза без разделителя не метка", "юридического адреса не указано", "", false, ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			c := extract("/п/x.docx", "docx", tt.line)
			if tt.value == "" {
				for _, it := range c.Items {
					if it.Kind == KindAddress {
						t.Errorf("адреса не ждали, получили %+v", it)
					}
				}
				return
			}
			it := cardFind(t, c, KindAddress, tt.value)
			if it.Valid != tt.valid {
				t.Errorf("Valid=%v (%s), хотим %v", it.Valid, it.Reason, tt.valid)
			}
			if !it.Valid && it.Reason == "" {
				t.Errorf("подозрительное значение без причины: %+v", it)
			}
			if it.Label != tt.label {
				t.Errorf("Label=%q, хотим %q", it.Label, tt.label)
			}
		})
	}
}

func TestExtractAddressCarriesAddress(t *testing.T) {
	// Критерий P2.2: у найденного значения есть адрес в источнике (P1.6),
	// Card.Traced учитывает новый вид.
	file := "/п/анкета.docx"
	fr := []trace.Fragment{
		{Ref: trace.Ref{File: file, Format: trace.FormatDocx, Page: 1, Para: 4},
			Text: "Юридический адрес: г. Москва, ул. Ленина, д. 1"},
	}
	c := Extract(file, "docx", fr)

	it := cardFind(t, c, KindAddress, "г москва ул ленина д 1")
	if len(it.Refs) != 1 || it.Refs[0].Page != 1 || it.Refs[0].Para != 4 {
		t.Errorf("адрес значения %+v, хотим страница 1 абзац 4", it.Refs)
	}
	if c.Traced != len(c.Items) {
		t.Errorf("Traced=%d из %d", c.Traced, len(c.Items))
	}
}

func TestExtractAddressXlsxCellAddress(t *testing.T) {
	// Новый вид адресуется клеткой листа, как числовые реквизиты (P1.6):
	// значение из строки-клетки несёт Sheet!Cell, а не только файл.
	c := extract("/п/форма2.xlsx", "xlsx", "Юридический адрес\tг. Москва, ул. Ленина, д. 1")

	it := cardFind(t, c, KindAddress, "г москва ул ленина д 1")
	if len(it.Refs) != 1 || it.Refs[0].Sheet != "Лист1" || it.Refs[0].Cell != "A1" {
		t.Errorf("адрес значения %+v, хотим Лист1!A1", it.Refs)
	}
}

func TestExtractAddressMergesRepeats(t *testing.T) {
	// Один адрес в шапке и в реквизитах договора — одно значение, два адреса.
	text := "Юридический адрес: г. Москва, ул. Ленина, д. 1\n" +
		"Место нахождения — г. Москва, улица Ленина, дом 1"
	c := extract("/п/x.docx", "docx", text)

	it := cardFind(t, c, KindAddress, "г москва ул ленина д 1")
	if it.Hits != 2 {
		t.Errorf("Hits=%d, хотим 2", it.Hits)
	}
	if it.RefTotal != 2 || len(it.Refs) != 2 {
		t.Errorf("адресов %d (сохранено %d), хотим 2", it.RefTotal, len(it.Refs))
	}
}
