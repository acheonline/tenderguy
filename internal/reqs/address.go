// addrTypeTokens — канонические токены частей адреса: признак «значение
// похоже на адрес» (валидация Item).
var addrTypeTokens = map[string]bool{
	"г": true, "ул": true, "д": true, "вл": true, "корп": true,
	"стр": true, "соор": true, "оф": true, "пом": true, "лит": true,
	"кв": true, "ком": true, "пер": true, "пр-кт": true, "б-р": true,
	"ш": true, "пл": true, "наб": true, "обл": true, "респ": true,
	"р-н": true, "дер": true, "с": true, "п": true, "мкр": true,
	"край": true,
}

// addrInvertTypes — подмножество addrTypeTokens для перестановки
// инвертированного порядка (addrInvert): типы, у которых прямой порядок —
// «тип + имя» («г. Москва», «ул. Ленина»), поэтому запись «Москва г»,
// «Ленина ул» — инверсия реестровой выписки. Двум остальным группам типов
// инверсия противопоказана: «д», «оф», «корп», «стр» и подобные всегда стоят
// перед номером («ул. Ленина, д. 1»), а «пр-кт», «б-р», «ш», «пл», «наб»,
// «пер» в прямом порядке стоят ПОСЛЕ имени («Невский пр-кт») — перестановка
// извратила бы корректный адрес.
var addrInvertTypes = map[string]bool{
	"г": true, "ул": true, "обл": true, "респ": true, "р-н": true,
	"дер": true, "с": true, "п": true, "мкр": true, "край": true,
}

// NormalizeAddress приводит адрес к форме, пригодной для сравнения (критерий 3
// P2.2): нижний регистр, «ё» → «е», разделители (запятые, точки, скобки,
// тире) — пробел, сокращения и полные слова частей адреса — к общей форме
// («ул.»/«улица» → «ул»), инвертированный порядок «имя + тип» («Москва г»,
// «Ленина ул») — к прямому «тип имя». Индекс (6 цифр) сохраняется как токен.
// Пустой результат означает, что нормализовывать было нечего, — SameAddress
// трактует это как «не найдено».
//
// Регионы и города не приводятся к кодам и не синонимизируются («СПб» и
// «Санкт-Петербург» — разные токены): сверка P2.3 сравнивает документы одного
// пакета, где такое расписание — редкость, а ложные слияния дороже.
func NormalizeAddress(s string) string {
	n := strings.ToLower(s)
	n = strings.ReplaceAll(n, "ё", "е")
	n = addrPunct.Replace(n)
	n = reAddrDash.ReplaceAllString(n, " ")
	tokens := strings.Fields(collapseSpace(n))
	for i, tok := range tokens {
		if canon, ok := addrCanon[tok]; ok {
			tokens[i] = canon
		}
	}
	return strings.Join(addrInvert(tokens), " ")
}

// SameAddress сравнивает два адреса после нормализации (критерий 4 P2.2).
// Контракт трёхзначный — см. Match.
func SameAddress(a, b string) Match {
	return compareNormalized(NormalizeAddress(a), NormalizeAddress(b))
}

// addrInvert меняет местами пару «имя + тип» на «тип + имя»: реестровые
// выписки пишут адрес в инвертированном порядке («Москва г», «Ленина ул»).
// Пара переставляется, только если за типом не следует ещё одно имя — иначе
// в «респ Татарстан г Казань» токен «г» ошибочно «отобрал» бы себе
// «Татарстан». Полная инверсия всех пар подряд («Татарстан респ Казань г»)
// этим правилом не лечится — осознанное ограничение: прямой порядок в
// документах пакета встречается на порядки чаще.
func addrInvert(tokens []string) []string {
	out := make([]string, len(tokens))
	copy(out, tokens)
	for i := 1; i < len(out); i++ {
		if !addrInvertTypes[out[i]] || !addrIsName(out[i-1]) {
			continue
		}
		if i+1 < len(out) && addrIsName(out[i+1]) {
			continue
		}
		out[i-1], out[i] = out[i], out[i-1]
	}
	return out
}

// addrIsName — токен похож на собственное имя (город, улица), а не на тип
// части адреса или номер: содержит букву и не начинается с цифры («5-а» —
// номер дома, а не имя).
func addrIsName(tok string) bool {
	if addrTypeTokens[tok] {
		return false
	}
	for i, r := range tok {
		if unicode.IsDigit(r) && i == 0 {
			return false
		}
		if unicode.IsLetter(r) {
			return true
		}
	}
	return false
}

// looksLikeAddress — валидация значения (критерий 6 P2.2): после нормализации
// в адресе есть хотя бы один канонический токен части адреса либо почтовый
// индекс (6 цифр). «уточняется» под адрес не проходит и помечается Valid=false.
func looksLikeAddress(norm string) bool {
	for _, tok := range strings.Fields(norm) {
		if addrTypeTokens[tok] {
			return true
		}
		if len(tok) == 6 && allDigits(tok) {
			return true
		}
	}
	return false
}
