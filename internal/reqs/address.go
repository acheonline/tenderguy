package reqs

// Задача P2.2: юридический адрес как реквизит карточки. Контракт тот же, что у
// остальных видов P1.5/P2.2: значение нормализовано, помечено меткой поля и
// адресом в источнике (P1.6), подозрительное — остаётся в карточке с
// Valid=false и причиной.
//
// Извлечение строго по метке юридического адреса: «почтовый адрес»,
// «электронный адрес» и «адрес поставки» — другие сущности, в сверке P2.3 они
// не заменяют место нахождения участника, поэтому отсекаются (списки
// addressSkip и addressPrevSkip). Адрес из печатей и рукописных фрагментов —
// вне скоупа, как и в постановке задачи.

import (
	"regexp"
	"strings"
	"unicode"

	"tenderguy/internal/trace"
)

// reAddressLabel — метки юридического адреса: «Юридический адрес: …»,
// «Адрес местонахождения — …», «Место нахождения: …», «Адрес регистрации»,
// а также голый «Адрес:» / «Адрес␉…» (клетка формы .xlsx).
//
// Группа 1 — квалифицирующая метка (для голого «адреса» не участвует в матче,
// m[2] == -1); группа 2 — значение: до первого таба, как и у наименования,
// чтобы в строке таблицы значением адреса не стали соседние колонки. После
// квалифицирующей метки обязателен непробуквенный символ: «юридического
// адреса не указано» не должно извлекать значение из продолжения фразы. У
// голой метки разделитель (: — – или таб) обязателен — «адрес поставки» без
// разделителя просто не матчится, а «Адрес: поставки…» добивает addressSkip.
var reAddressLabel = regexp.MustCompile(
	`(?i)(?:` +
		`(юридическ(?:ий|ого)\s+адрес|юрид\.\s*адрес|адрес\s+мест[а-яё]?\s*нахождени[а-яё]+|мест[а-яё]?\s*нахождени[а-яё]+|адрес\s+регистрации)[^\p{L}]` +
		`|адрес(?:\s*\([^)]*\))?[\t ]*[:—–\t]` +
		`)[\t ]*(?:\([^)]*\))?[\t ]*[:—–-]?[\t ]*([^\t]+)`)

// addressSkip — значения, которые метка «адрес» описывает помимо места
// нахождения: адрес поставки/объекта/склада, электронная почта и сайт, адрес
// организатора закупки. Проверяется первое слово значения.
var addressSkip = map[string]bool{
	"поставки": true, "поставка": true, "доставки": true, "доставка": true,
	"получения": true, "отгрузки": true,
	"объект": true, "объекта": true, "объектов": true,
	"выполнения": true, "оказания": true, "производства": true,
	"склада": true, "хранения": true, "покупки": true,
	"товара": true, "товаров": true, "продукции": true,
	"оборудования": true, "работ": true, "услуг": true,
	"почты": true, "электронной": true, "электронный": true,
	"e-mail": true, "email": true, "сайта": true, "сайт": true,
	"www": true, "http": true, "https": true,
	"закупки": true, "торгов": true, "площадки": true, "организатора": true,
}

// addressPrevSkip — слово перед голым «адрес»: «почтовый адрес» и
// «электронный адрес» — не юридический адрес участника.
var addressPrevSkip = map[string]bool{
	"почтовый": true, "почтовому": true, "почтовых": true,
	"электронный": true, "электронному": true, "электронных": true,
	"фактический": true, "фактическому": true,
	"интернет": true, "веб": true, "обратный": true, "домашний": true,
}

// scanAddress извлекает юридический адрес по метке (критерий 1 P2.2).
// Значение без признаков адреса (индекс, тип населённого пункта, улица, дом)
// помечается Valid=false и остаётся в карточке — как наименование без ОПФ.
func (c *Card) scanAddress(frag trace.Fragment, pos int, line string) {
	for _, m := range reAddressLabel.FindAllStringSubmatchIndex(line, -1) {
		if m[2] == -1 && addressPrevSkip[lastWord(line[:m[0]])] {
			continue
		}
		raw := cleanValue(line[m[4]:m[5]])
		if raw == "" || addressSkip[firstWord(raw)] || strings.ContainsRune(raw, '@') {
			continue
		}
		norm := NormalizeAddress(raw)
		if norm == "" {
			continue
		}
		ok := looksLikeAddress(norm)
		item := Item{
			Kind: KindAddress, Value: norm, Raw: raw, Valid: ok,
			Label: matchedLabel(line, m[0], m[4]),
		}
		if !ok {
			item.Reason = "значение не содержит признаков адреса: индекса, типа населённого пункта, улицы или дома"
		}
		c.add(located(frag, pos, m[4], item))
	}
}

// addrPunct — разделители частей адреса заменяются пробелом: запятые между
// частями ставятся произвольно («190000, г. Санкт-Петербург» и «190000 г
// Санкт-Петербург» — один адрес), точка принадлежит сокращению («ул.»), скобки
// — уточнению («д. 5 (литер А)»).
var addrPunct = strings.NewReplacer(
	",", " ", ".", " ", ";", " ", ":", " ",
	"«", " ", "»", " ", "\"", " ", "'", " ",
	"(", " ", ")", " ", "!", " ", "?", " ",
)

// reAddrDash — тире как разделитель частей адреса («г. Москва — ул. Ленина»).
// Дефис без пробелов вокруг не трогается: он часть номера («д. 5-а») или
// сокращения («пр-кт», «р-н»).
var reAddrDash = regexp.MustCompile(`(?:^|\s)[–—-](?:\s|$)`)

// addrCanon — токены адресных частей к общей форме (критерий 3 P2.2):
// «ул.», «улица» и «улицы» дают «ул», поэтому «ул. Ленина» и «улица Ленина»
// нормализуются одинаково. Ключи — уже в нижнем регистре и без точек:
